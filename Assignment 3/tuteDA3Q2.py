# Task 2: Using the Math Module for Calculations

import math as mt

num = int(input("Enter a number: "))

print(f"Square root: {mt.sqrt(num)}")
print(f"Logarithm: {mt.log(num)}")
print(f"Sine: {mt.sin(num)}")

